create table if not exists public.property_management_submissions (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  candidate_name text not null
    check (char_length(candidate_name) between 1 and 120),
  score integer not null check (score between 0 and 100),
  score_band text not null
    check (score_band in ('Excellent', 'Good', 'Adequate', 'Below 60')),
  passed boolean not null check (passed = (score >= 75)),
  elapsed_seconds integer not null check (elapsed_seconds between 0 and 2100),
  auto_submitted boolean not null default false,
  section_scores jsonb not null
    check (jsonb_typeof(section_scores) = 'object'),
  answers jsonb not null
    check (jsonb_typeof(answers) = 'array' and jsonb_array_length(answers) = 15),
  submitted_at timestamptz not null default timezone('utc', now())
);
create unique index if not exists property_management_submissions_session_id_key
  on public.property_management_submissions (session_id);
create index if not exists property_management_submissions_submitted_at_idx
  on public.property_management_submissions (submitted_at desc);
create index if not exists property_management_submissions_candidate_name_idx
  on public.property_management_submissions (candidate_name);

alter table public.property_management_submissions enable row level security;
revoke all on public.property_management_submissions from anon, authenticated;
revoke all on sequence public.property_management_submissions_id_seq from anon, authenticated;
