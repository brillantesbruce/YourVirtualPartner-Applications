create table if not exists public.digital_marketing_submissions (
  id bigint generated by default as identity primary key,
  session_id uuid not null,
  candidate_name text not null
    check (char_length(candidate_name) between 1 and 120),
  score integer not null check (score between 0 and 40),
  percentage integer not null check (percentage between 0 and 100),
  passed boolean not null check (passed = (score >= 30)),
  elapsed_seconds integer not null check (elapsed_seconds between 0 and 3600),
  auto_submitted boolean not null default false,
  section_scores jsonb not null
    check (jsonb_typeof(section_scores) = 'object'),
  answers jsonb not null
    check (jsonb_typeof(answers) = 'array' and jsonb_array_length(answers) = 40),
  submitted_at timestamptz not null default timezone('utc', now())
);
create unique index if not exists digital_marketing_submissions_session_id_key
  on public.digital_marketing_submissions (session_id);
create index if not exists digital_marketing_submissions_submitted_at_idx
  on public.digital_marketing_submissions (submitted_at desc);
create index if not exists digital_marketing_submissions_candidate_name_idx
  on public.digital_marketing_submissions (candidate_name);

alter table public.digital_marketing_submissions enable row level security;
revoke all on public.digital_marketing_submissions from anon, authenticated;
revoke all on sequence public.digital_marketing_submissions_id_seq from anon, authenticated;
